def _png_with_exif(path):
    im = Image.new("RGB", (64, 64), (30, 90, 160))
    ex = im.getexif()
    ex[306] = "2025:03:14 09:26:53"  # DateTime
    ex[271], ex[272] = "SyntheticCam", "Demo-1"
    im.save(path, exif=ex)


def _docx_macro(path):
    core = ('<cp:coreProperties xmlns:cp="a" xmlns:dc="b" xmlns:dcterms="c"><dc:creator>Synthetic Author</dc:creator>'
            '<dcterms:created>2025-04-10T12:00:00Z</dcterms:created><dcterms:modified>2025-04-09T08:30:00Z</dcterms:modified></cp:coreProperties>')
    with zipfile.ZipFile(path, "w") as z:
        z.writestr("word/document.xml", "<w:document/>")
        z.writestr("docProps/core.xml", core)
        z.writestr("word/vbaProject.bin", b"SYNTHETIC-INERT-PLACEHOLDER")


FILES = {
    "meeting_notes.txt": lambda p: p.write_text("SYNTHETIC DEMO FILE\nQuarterly planning notes.\nNothing unusual here.\n"),
    "photo_sample.png": _png_with_exif,
    "quarterly_report.pdf": lambda p: p.write_bytes(b"%PDF-1.4\n/Title (SYNTHETIC Quarterly Report)\n/Author (Demo Author)\n/CreationDate (D:20250201090000)\n%%EOF\n"),
    "budget_macro.docx": _docx_macro,
    "invoice.pdf.exe": lambda p: p.write_bytes(b"MZ" + b"\x00" * 512),
    "update_script.txt": lambda p: p.write_text("SYNTHETIC: # demo text containing keywords\npowershell -enc ... (inert text)\nchmod +x run.sh\n"),
    "renamed_image.pdf": _png_with_exif,
    "hr_policy_active.pdf": lambda p: p.write_bytes(b"%PDF-1.4\n/Title (SYNTHETIC)\n/OpenAction << /S /JavaScript /JS (inert) >>\n%%EOF\n"),
}

CASES = [
    ("SYNTHETIC: Workstation document review", "Demonstration case. Fictional documents reviewed for metadata consistency.", "medium",
     ["meeting_notes.txt", "photo_sample.png", "quarterly_report.pdf"]),
    ("SYNTHETIC: Suspicious attachment triage", "Demonstration case with deliberately odd synthetic samples to exercise the rules and the AI triage.", "high",
     ["budget_macro.docx", "invoice.pdf.exe", "update_script.txt", "renamed_image.pdf", "hr_policy_active.pdf"]),
]


def seed(db):
    admin = db.query(models.User).join(models.Role).filter(models.Role.name == "administrator").first()
    if not admin:
        raise SystemExit("Create an administrator first")
    if db.query(models.Case).filter_by(is_synthetic=True).first():
        print("demo data already present")
        return
    inv = db.query(models.User).filter_by(username="demo_investigator").first()
    if not inv:
        pw = "Demo-" + secrets.token_urlsafe(12) + "9a"
        inv = create_user(db, "demo_investigator", "Demo Investigator (synthetic)", pw, "investigator")
        print(f"created demo_investigator with generated password (shown once): {pw}")
    tmp = Path(tempfile.mkdtemp())
    for title, desc, prio, files in CASES:
        case = models.Case(case_id=ops.next_id(db, models.Case, None, "CASE"), title=title, description=desc, priority=prio,
                           investigator_id=inv.id, is_synthetic=True, created_at=utcnow() - timedelta(days=3))
        db.add(case)
        db.flush()
        records.audit(db, admin.username, "case.create", {"case": case.case_id, "synthetic": True})
        for fname in files:
            src = tmp / f"{case.case_id}_{fname}"
            FILES[fname](src)
            ev = ops.ingest(db, case, inv, src, fname, "", "SYNTHETIC sample generated by seed script", is_synthetic=True)
            db.flush()
            ops.analyze(db, ev, inv)
        db.commit()
    print("seeded synthetic demo cases")
